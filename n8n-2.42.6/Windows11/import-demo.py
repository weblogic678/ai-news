"""Create inactive demo workflows using the fixed n8n 2.42.6 Server CLI.
Requires completed owner setup. Stops/restarts this kit's n8n during the import.
Does not import account credentials, execute workflows, or overwrite workflow IDs.
"""
import argparse,json,re,secrets,subprocess,sys
from pathlib import Path
from demo_common import check_kit,checkpoint,digest,existing,save

BASE=Path(__file__).resolve().parent

def compose(meta,runtime,args,stdin=None):
    return subprocess.run(['docker','compose','--project-name',meta['project'],*args],cwd=runtime,input=stdin,capture_output=True,text=True, encoding="utf-8",check=True,timeout=180).stdout

def job(meta,runtime,entrypoint,args,stdin=None):
    helper='ai-news-demo-helper-'+secrets.token_hex(16)
    try:return compose(meta,runtime,['run','--name',helper,'--rm','--no-deps','-T','--entrypoint',entrypoint,'n8n',*args],stdin)
    except subprocess.TimeoutExpired:
        # Killing a timed-out Docker client doesn't necessarily stop its container.
        # Only remove the uniquely named temporary helper owned by this exact call.
        try:subprocess.run(['docker','rm','-f',helper],capture_output=True,timeout=15,check=False)
        except Exception:pass
        raise

def exported(meta,runtime,workflow_id,path):
    job(meta,runtime,'n8n',['export:workflow','--id='+workflow_id,'--output='+path])
    value=json.loads(job(meta,runtime,'cat',[path]));items=value if isinstance(value,list) else [value]
    if len(items)!=1 or items[0].get('id')!=workflow_id or items[0].get('active') is not False:
        raise RuntimeError('Export verification did not find exactly the expected inactive workflow.')
    return items[0]

def import_files(meta,runtime,paths,state,state_path,user_id=None):
    pending=[]
    for file in paths:
        sha=digest(file);old=existing(state,file.name,sha)
        if old:continue
        data=json.loads(file.read_text(encoding='utf-8'));data['id']=secrets.token_urlsafe(12);data['active']=False
        if any(n.get('credentials') for n in data['nodes']):raise RuntimeError('Bundle unexpectedly contains credentials.')
        pending.append((file,sha,data))
    running=compose(meta,runtime,['ps','--status','running','--services']).splitlines()
    if 'n8n' not in running:raise RuntimeError('Start this kit first and complete owner setup before importing.')
    job_path='/home/node/.n8n/ai-news-demo-'+secrets.token_hex(16)
    compose(meta,runtime,['stop','n8n'])
    try:
        # Node writes into the persistent volume using the image's regular node user.
        # Public bundled workflow data is supplied via stdin, never a shell command string.
        job(meta,runtime,'node',['-e',"const fs=require('fs');const dir=process.argv[1];fs.mkdirSync(dir,{mode:0o700});fs.writeFileSync(dir+'/batch.json',fs.readFileSync(0),{mode:0o600});",job_path],json.dumps([x[2] for x in pending]))
        if pending:
            for file,sha,data in pending:state['workflows'][file.name]={'sha256':sha,'state':'attempting','workflow_id':data['id']}
            save(state_path,state)
            flags=['import:workflow','--input='+job_path+'/batch.json','--activeState=false']
            if user_id:flags.append('--userId='+user_id)
            job(meta,runtime,'n8n',flags)
        for index,file in enumerate(paths):
            item=state['workflows'][file.name]
            result=exported(meta,runtime,item['workflow_id'],job_path+'/verify-'+str(index)+'.json')
            expected=json.loads(file.read_text(encoding='utf-8'))
            if result['name']!=expected['name'] or result['connections']!=expected['connections']:
                raise RuntimeError('Imported workflow differs from expected demo. Inspect it manually.')
            item['state']='completed';save(state_path,state)
            print('Verified inactive workflow:',file.name,item['workflow_id'])
        print('Created/verified demo workflows. No workflow execution, publishing or model charge has been triggered.')
    finally:
        # This path was generated by this run; never remove an arbitrary user path.
        try:job(meta,runtime,'node',['-e',"require('fs').rmSync(process.argv[1],{recursive:true,force:true});",job_path])
        except Exception:pass
        compose(meta,runtime,['up','-d','--pull','never','n8n'])

def main():
    p=argparse.ArgumentParser();p.add_argument('--user-id');p.add_argument('--dry-run',action='store_true');args=p.parse_args()
    if args.user_id and not re.fullmatch(r'[a-fA-F0-9-]{36}',args.user_id):raise RuntimeError('Expected an existing user UUID; no users are created.')
    paths=[BASE/'workflows/01-smoke.json',BASE/'workflows/02-deepseek.json']
    if args.dry_run:
        print('Plan: stop this kit, import NEW random IDs to the owner personal project, verify exported inactive workflows, restart. No execution.')
        for file in paths:print(file.name,digest(file))
        return
    meta,runtime=check_kit(BASE,'n8n')
    with checkpoint(runtime,'n8n:'+meta['project']) as (state,state_path):
        import_files(meta,runtime,paths,state,state_path,args.user_id)

if __name__=='__main__':
    try:main()
    except subprocess.CalledProcessError:
        print('FAILED: Docker/CLI operation failed. Check local logs and retained import checkpoint before retrying.',file=sys.stderr);sys.exit(1)
    except subprocess.TimeoutExpired:
        print('FAILED: Docker operation timed out. Confirm no helper is still running before retrying; checkpoint retained.',file=sys.stderr);sys.exit(1)
    except (RuntimeError,OSError,ValueError) as e:
        print('FAILED:',str(e),file=sys.stderr);sys.exit(1)
